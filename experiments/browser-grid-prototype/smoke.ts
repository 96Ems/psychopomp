// Real component/rAF verification in a disposable browser, separate from timing.
import { chromium } from "playwright-core";
import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
const output = resolve(import.meta.dir, "../../output/browser-perf/smoke");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME || "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser", headless: true, args: ["--enable-gpu"] });
const context = await browser.newContext({ viewport: { width: 1920, height: 1200 }, recordVideo: { dir: output, size: { width: 1920, height: 1200 } } });
try {
  const page = await context.newPage();
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(String(e)));
  page.on("console", e => { if (e.type() === "error") errors.push(e.text()); });
  await page.goto(process.env.SMOKE_URL || "http://127.0.0.1:5202/");
  await page.waitForFunction(() => !!(window as any).probe?.state);
  await page.getByRole("button", { name: "Next →", exact: true }).click();
  await page.waitForFunction(() => (window as any).probe.state.step === 1 && (window as any).probe.state.time > .15);
  await page.getByRole("button", { name: "Pause / resume", exact: true }).click();
  await page.waitForFunction(() => (window as any).probe.state.phase === "Paused");
  const before = await page.evaluate(() => (window as any).probe.state.time);
  await page.getByRole("button", { name: "+1 frame", exact: true }).click();
  await page.waitForFunction(before => Math.abs((window as any).probe.state.time - before - 1/60) < 1e-6, before);
  await page.getByRole("button", { name: /Speed ·/ }).click();
  await page.waitForFunction(() => (window as any).probe.state.speed === "0.5x");
  await page.getByRole("button", { name: "Pause / resume", exact: true }).click();
  await page.locator("canvas").focus();
  await page.keyboard.press("End");
  await page.waitForFunction(() => (window as any).probe.state.step === 8 && (window as any).probe.state.phase === "Held");
  await page.locator("canvas").screenshot({ path: resolve(output, "held.png") });
  const heldTime = await page.evaluate(() => (window as any).probe.state.time);
  await page.locator('select[name="theme"]').selectOption("black");
  await page.waitForFunction(() => (window as any).probe.frame === 0);
  if (await page.evaluate(() => (window as any).probe.state.time) !== heldTime) throw new Error("Theme advanced clock");
  await page.locator("canvas").screenshot({ path: resolve(output, "black.png") });
  await page.getByRole("button", { name: "Reduced motion", exact: true }).click();
  await page.waitForFunction(() => (window as any).probe.state.reduced);
  await page.getByRole("button", { name: "← Previous", exact: true }).click();
  await page.waitForFunction(() => (window as any).probe.state.step === 7 && (window as any).probe.state.phase === "Held");
  await page.locator('select[name="scene"]').selectOption("grid-isomorphism");
  await page.waitForFunction(() => (window as any).probe.state.title.includes("different way"));
  await page.getByRole("button", { name: "Next →", exact: true }).click();
  await page.waitForFunction(() => (window as any).probe.state.step === 1 && (window as any).probe.state.phase === "Held");
  await page.locator("canvas").screenshot({ path: resolve(output, "regroup.png") });
  await page.evaluate(() => document.querySelector("kinograph-canvas")!.remove());
  if (errors.length) throw new Error(errors.join("\n"));
  const video = page.video();
  await context.close();
  await video?.saveAs(resolve(output, "navigation.webm"));
  console.log("PASS: rAF navigation, pause, exact frame step, speed, theme clock stability, reduced motion, scene change, teardown; no browser errors");
} finally { await browser.close(); }
